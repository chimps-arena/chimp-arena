"use client";

import { motion } from "motion/react";

/**
 * Shared scroll-reveal wrapper (fade + rise, once per element) - the
 * "feels alive while navigating" polish the founder asked for, applied
 * consistently instead of one-off animations per page.
 */
export function Reveal({
  children,
  delay = 0,
  className,
}: {
  children: React.ReactNode;
  delay?: number;
  className?: string;
}) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y: 20 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-60px" }}
      transition={{ duration: 0.55, delay, ease: [0.22, 1, 0.36, 1] }}
    >
      {children}
    </motion.div>
  );
}
